import assert from 'node:assert/strict';
import { createResponseGate } from '../src/lib/voice/responseGate.ts';

const gate = createResponseGate();
const first = gate.start();
assert.equal(gate.isCurrent(first), true);
assert.equal(gate.markSent(first), true);
assert.equal(gate.created('response-old'), true);
assert.equal(gate.accepts('response-old'), true);
assert.equal(gate.cancel(), true);
assert.equal(gate.accepts('response-old'), false);
assert.equal(gate.isCurrent(first), false);
assert.equal(gate.finish('response-old'), false);
const second = gate.start();
assert.equal(gate.markSent(first), false);
assert.equal(gate.markSent(second), true);
assert.equal(gate.created('response-new'), true);
assert.equal(gate.accepts('response-old'), false);
assert.equal(gate.accepts('response-new'), true);
assert.equal(gate.finish('response-old'), false);
assert.equal(gate.finish('response-new'), true);
assert.equal(gate.cancel(), false);
const unsent = gate.start();
assert.equal(gate.cancel(), false);
assert.equal(gate.markSent(unsent), false);

const race = createResponseGate();
const a = race.start();
assert.equal(race.markSent(a), true);
assert.equal(race.cancel(), true);
const b = race.start();
assert.equal(race.isBlocked(), true);
assert.equal(race.markSent(b), false);
assert.equal(race.created('old'), false);
assert.equal(race.accepts('old'), false);
assert.equal(race.finish('old'), false);
assert.equal(race.isBlocked(), false);
assert.equal(race.markSent(b), true);
assert.equal(race.created('new'), true);
assert.equal(race.accepts('old'), false);
assert.equal(race.accepts('new'), true);

const timeout = createResponseGate();
const pending = timeout.start();
timeout.markSent(pending);
timeout.cancel();
const waiting = timeout.start();
assert.equal(timeout.isBlocked(), true);
timeout.failWaiting();
assert.equal(timeout.isCurrent(waiting), false);
assert.equal(timeout.isBlocked(), true);
